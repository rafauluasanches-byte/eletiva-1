CREATE TABLE procedimentos (
	idproc INT AUTO_INCREMENT PRIMARY KEY,
	nomeProc VARCHAR(100) NOT NULL,
	preco DECIMAL(10, 2) NOT NULL,
	profi VARCHAR(100) NOT NULL
);

CREATE TABLE cliente (
	id INT AUTO_INCREMENT PRIMARY KEY,
	nomeCli VARCHAR(100) NOT NULL,
	telefoneCli VARCHAR(20) NOT NULL,
	cpfCli VARCHAR(14) NOT NULL,
	enderecoCli VARCHAR(255) NOT NULL
);

CREATE TABLE profissionais (
	idprofi INT AUTO_INCREMENT PRIMARY KEY,
	nomeProfi VARCHAR(100) NOT NULL,
	telefoneProfi VARCHAR(20) NOT NULL,
	cnpjProfi VARCHAR(18) NOT NULL,
	enderecoProfi VARCHAR(255) NOT NULL
);
